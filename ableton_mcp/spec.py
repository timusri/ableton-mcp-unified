"""THE spec table: single source of truth for every MCP tool and Remote Script command.

* ``SPECS``: one ``ToolSpec`` per tool. ``manual=True`` rows are implemented in
  ``tools_manual.py``; all others are built by ``tools_generated.py``.
* ``HIDDEN_SPECS``: Remote Script commands without a dedicated tool. They are
  documented, contribute to ``MODIFYING_COMMANDS`` and are callable through the
  ``send_command`` tool.
* ``MODIFYING_COMMANDS`` is derived from these rows; ``tests/unit/test_spec_table.py``
  asserts it equals the Remote Script registry's ``modifying_commands()``.

Conventions: 1-based indices everywhere (``Param.index`` / ``optional_index`` / ``index_list``),
normalized 0-1 device parameter values, responses echo ``*_index`` + ``*_name``.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, List, Tuple

REQUIRED = object()


@dataclass(frozen=True)
class Param:
    name: str
    type: str                     # int | float | str | bool | list | list[int] | list[str] | list[dict] | dict | any
    default: Any = REQUIRED
    doc: str = ""
    index: bool = False           # required 1-based index -> 0-based
    optional_index: bool = False  # 1-based, 0 = unset -> None (or rs_default)
    index_list: bool = False      # list of 1-based indices
    rs_name: str | None = None    # wire name when different from the tool param name
    rs_default: Any = None        # value sent when optional_index is unset (default: omitted)

    @property
    def required(self) -> bool:
        return self.default is REQUIRED


@dataclass(frozen=True)
class ToolSpec:
    name: str
    command: str
    category: str
    doc: str
    params: Tuple[Param, ...] = ()
    modifying: bool = False
    echo: Tuple[str, ...] = ()
    deprecated_aliases: Tuple[str, ...] = ()
    format: str = "json"
    manual: bool = False
    hidden: bool = False


def P(name, type, default=REQUIRED, doc="", index=False, optional_index=False, index_list=False, rs_name=None, rs_default=None):
    return Param(name, type, default, doc, index, optional_index, index_list, rs_name, rs_default)


def T(name, command, category, doc, params=(), modifying=None, echo=(), deprecated_aliases=(), format="json", manual=False, hidden=False):
    if modifying is None:
        modifying = _RS_MODIFYING.get(command, False)
    return ToolSpec(name, command, category, doc, tuple(params), modifying, tuple(echo), tuple(deprecated_aliases), format, manual, hidden)


